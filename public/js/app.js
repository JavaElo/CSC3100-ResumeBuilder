const ResumeList = document.getElementById('ResumeList');
const emptyState = document.getElementById('emptyState');
const submitBtn = document.getElementById('submitBtn');
const btnText = document.getElementById('btnText');
        
let ResumeCount = 0


submitBtn.addEventListener('click', async (e) => {
    e.preventDefault()
    const title = document.getElementById('title').value.trim()
    const details = document.getElementById('details').value.trim()
    const key = document.getElementById('apiKey').value.trim()

    submitBtn.disabled = true
    btnText.innerText = "Crafting the BEST resume"

    try {
        const response = await fetch(`http://localhost:8000/gen-resume?title=${encodeURIComponent(title)}&details=${encodeURIComponent(details)}&key=${encodeURIComponent(key)}`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body:
                JSON.stringify({title, details, key})
        })
    } catch (err) {
        alert("Couldn't generate a response! Is the server running?")
    } finally {
        const res = await fetch(`http://localhost:8000/gen-resume?title=${encodeURIComponent(title)}&details=${encodeURIComponent(details)}&key=${encodeURIComponent(key)}`)
        const data = await res.json()
        addResumeCard(data, data.title, data.details, data.story, new Date().toISOString())
        submitBtn.disabled = false
        btnText.innerText = "Generate Resume"
    }
});

function addResumeCard(data, title, details, text, dateStr) {
    emptyState.classList.add('hidden')
    const date = new Date(dateStr).toLocaleDateString()
    const card = document.createElement('div')
    console.log(data)
    card.className ="p-8 rounded-3xl cursor-pointer group transition-all relative " + "bg-gradient-to-br from-slate-900/60 to-slate-800/40 backdrop-blur-xl " + "border border-cyan-500/30 shadow-[0_0_25px_rgba(0,255,255,0.15)] " + "hover:shadow-[0_0_40px_rgba(0,255,255,0.35)] hover:border-cyan-400/40"

    //Use of AI: Responsible for css contents, expanded on the idea used in our story Ai discussed in class
    //Didn't generate a prompt here, just looked back at previous output from html body that had css within its classes to match the style here
    data.forEach(block => {
    card.innerHTML = `
        <div class="mb-6">
            <span class="text-xs font-bold uppercase tracking-widest text-cyan-400 
                        drop-shadow-[0_0_6px_rgba(0,255,255,0.6)]">
                ${block.details}
            </span>

            <h4 class="text-3xl font-extrabold mt-1 
                    text-cyan-300 tracking-wide 
                    drop-shadow-[0_0_12px_rgba(0,255,255,0.5)]">
                ${block.title} Resume
            </h4>
        </div>

        <div class="story-content text-slate-300 leading-relaxed font-medium mb-8 
                    italic whitespace-pre-line transition-all duration-500 
                    bg-slate-900/40 border border-cyan-500/20 rounded-2xl p-6 
                    shadow-[0_0_20px_rgba(0,255,255,0.15)] 
                    group-hover:shadow-[0_0_30px_rgba(0,255,255,0.25)]">
            "${block.text}"
        </div>

        <div class="flex items-center justify-between text-[10px] 
                    text-cyan-500/70 font-bold uppercase tracking-wider 
                    border-t border-cyan-500/20 pt-3">
                    
            <span class="drop-shadow-[0_0_6px_rgba(0,255,255,0.4)]">
                Generated by GoogleGenAi • ${block.date}
            </span>

            <span class="read-more-hint text-cyan-300 
                          hover:text-cyan-200 transition-all 
                        drop-shadow-[0_0_6px_rgba(0,255,255,0.5)]">
                Expand ↓
            </span>
        </div>
    `})

    card.addEventListener('click', () => {
        const content = card.querySelector('.story-content')
        const hint = card.querySelector('.read-more-hint')
                
        const isCollapsed = content.classList.contains('line-clamp-3')
        content.classList.toggle('line-clamp-3', !isCollapsed)
        hint.innerText = isCollapsed ? "Click to collapse ↑" : "Click to read more ↓"
    })
            
    ResumeList.prepend(card)
    ResumeCount++
    document.getElementById('ResumeCount').innerText = `${ResumeCount} Resumes`
}